def decoder(morceaux):
    return base64.b64decode("".join(morceaux)).decode("utf-8")


def appliquer_modifications(racine):
    print("-" * 70)
    print("ETAPE 1/2 : modification des fichiers existants")
    print("-" * 70)

    tout_ok = True

    for modif in MODIFICATIONS_B64:
        chemin_relatif = modif["chemin"]
        description = modif["description"]
        ancien = decoder(modif["ancien_b64"])
        nouveau = decoder(modif["nouveau_b64"])

        chemin_absolu = os.path.join(racine, chemin_relatif)

        print("  * " + chemin_relatif + " (" + description + ")")

        if not os.path.isfile(chemin_absolu):
            print("    [ECHEC] fichier introuvable -- avez-vous bien lance les scripts precedents ?")
            tout_ok = False
            continue

        with open(chemin_absolu, "r", encoding="utf-8") as f:
            contenu = f.read()

        if contenu == nouveau:
            print("    [SKIP] deja applique.")
            continue

        if contenu != ancien:
            print("    [ECHEC] le contenu actuel de ce fichier ne correspond ni a l'ancienne")
            print("    version attendue, ni a la nouvelle -- il a probablement ete modifie")
            print("    depuis. Recopiez-moi son contenu complet pour que j'adapte le script.")
            tout_ok = False
            continue

        with open(chemin_absolu, "w", encoding="utf-8", newline="") as f:
            f.write(nouveau)
            f.flush()
            os.fsync(f.fileno())

        with open(chemin_absolu, "r", encoding="utf-8", newline="") as f:
            relu = f.read()

        if relu != nouveau:
            print("    [ECHEC VERIFICATION] le contenu relu ne correspond pas.")
            tout_ok = False
            continue

        print("    [OK VERIFIE]")

    print()
    return tout_ok


def creer_migration(racine):
    print("-" * 70)
    print("ETAPE 2/2 : migration de base de donnees")
    print("-" * 70)

    contenu_cible = decoder(MIGRATION_B64)
    chemin_absolu = os.path.join(racine, MIGRATION_CHEMIN)

    if os.path.isfile(chemin_absolu):
        with open(chemin_absolu, "r", encoding="utf-8") as f:
            contenu_actuel = f.read()

        if contenu_actuel == contenu_cible:
            print("  [SKIP] " + MIGRATION_CHEMIN + " : deja present.")
            return True

        print("  [ATTENTION] " + MIGRATION_CHEMIN + " existe deja avec un contenu different -- non touche.")
        return False

    dossier = os.path.dirname(chemin_absolu)
    if dossier and not os.path.isdir(dossier):
        os.makedirs(dossier, exist_ok=True)

    with open(chemin_absolu, "w", encoding="utf-8", newline="") as f:
        f.write(contenu_cible)
        f.flush()
        os.fsync(f.fileno())

    with open(chemin_absolu, "r", encoding="utf-8", newline="") as f:
        relu = f.read()

    if relu != contenu_cible:
        print("  [ECHEC VERIFICATION] le contenu relu ne correspond pas.")
        return False

    print("  [OK VERIFIE] " + MIGRATION_CHEMIN)
    return True


def verifier_syntaxe_php(racine):
    print()
    print("-" * 70)
    print("Verification de la syntaxe PHP")
    print("-" * 70)

    fichiers_php = [m["chemin"] for m in MODIFICATIONS_B64 if m["chemin"].endswith(".php")]
    fichiers_php.append(MIGRATION_CHEMIN)

    for chemin_relatif in fichiers_php:
        chemin_absolu = os.path.join(racine, chemin_relatif)

        if not os.path.isfile(chemin_absolu):
            continue

        try:
            resultat = subprocess.run(
                ["php", "-l", chemin_absolu],
                capture_output=True, text=True, timeout=30
            )
            sortie = (resultat.stdout.strip() + resultat.stderr.strip())
            if "No syntax errors" not in sortie:
                print("  [ATTENTION] " + chemin_relatif + " : " + sortie)
            else:
                print("  [OK] " + chemin_relatif)
        except Exception as exception:
            print("  (php -l non disponible : " + str(exception) + ")")
            break

    print()


